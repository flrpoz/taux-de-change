import assert from 'node:assert/strict';
import {calculate,defaults,number} from '../dist/engine.mjs';
const rates={rbc:{rate:1.5},bnc:{rate:1.51},wise:{rate:1.49}};
let r=calculate(100,'EUR','other',defaults,rates,{wiseFee:1});
assert.equal(r.find(x=>x.id==='rbc').base,150);
assert.equal(r.find(x=>x.id==='rbc').fee,3.75);
assert.equal(r.find(x=>x.id==='rbc').reward,1.5);
assert.ok(Math.abs(r.find(x=>x.id==='rbc').float-153.75*((1.08)**(21/365)-1))<1e-10);
assert.equal(r[0].id,'wise');
assert.equal(calculate(100,'EUR','other',defaults,rates).find(x=>x.id==='wise').fee,149*0.0075);
assert.equal(calculate(100,'EUR','other',{...defaults,waiver:true},rates).find(x=>x.id==='bnc').fee,0);
assert.equal(calculate(100,'EUR','other',{...defaults,days:0},rates)[0].float,0);
assert.equal(calculate(100,'EUR','travel',defaults,rates).find(x=>x.id==='rbc').reward,1.875);
assert.equal(calculate(100,'EUR','food',{...defaults,monthly:2450},rates).find(x=>x.id==='bnc').points,50*5+101*2);
assert.equal(calculate(100,'EUR','food',{...defaults,monthly:2600},rates).find(x=>x.id==='bnc').points,151*2);
assert.equal(calculate(100,'CAD','other',defaults,{}).find(x=>x.id==='wise').net,100);
assert.equal(calculate(100,'EUR','other',{...defaults,estimates:false},{rbc:{rate:1.5,estimated:true}}).find(x=>x.id==='rbc').net,null);
assert.equal(calculate(100,'EUR','other',defaults,{}).every(x=>x.net===null),true);
assert.equal(calculate(100,'EUR','other',defaults,{}, {wise:{rate:1.5},wiseFee:0}).find(x=>x.id==='wise').net,150);
assert.equal(number('1 234,56'),1234.56);assert.ok(Number.isNaN(number('abc')));
assert.ok(r.every((x,i)=>i===0||x.net>=r[i-1].net));
assert.equal(calculate(100,'CAD','other',defaults,{}).find(x=>x.id==='rbc').fee,0);
console.log('15 scénarios vérifiés : FX, points, seuil BNC, délai, classement, données absentes et saisie française.');
